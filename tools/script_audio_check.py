# 대본이 '귀로 들을 때' 틀리게 들릴 표현과 영상·리포트 개수 어긋남을 TTS 전에 본다(운영자 영상 검토 2026-10-29, CBRS 43회차).
#  - '리포트 일부/오부의 표' → '일부(some)·오부'로 들림 → '리포트 N번째 부분'으로
#  - '국면 비/씨' → '국면비·국면시'로 뭉개짐 → '두 번째 국면(공급 소화 단계)'처럼 풀어 읽기
#  - '닷새·여드레·나흘'(발음 불명확, 통합 제작·검수 지침 3.2 → 'N 거래일'),  '쌓인 일감'(사인 일감), '신고서에 적힌 시가'(시간) → '다섯 거래일', '수주 잔고', '시장 가격'
#  - 가설 세 개를 말한 뒤 '네 시나리오마다' → 개수 어긋남. 리포트 시나리오가 더 많으면 다리 문장('영상에서 다룬 세 가설 외에 …까지 네 가지')
#  - '몇 번이었을까요?'로 묻고 답 숫자를 영상에서 하나도 말하지 않음 → 결론 한 줄(N번 중 M번)은 영상에서, 상세 표는 리포트로
#  - v2.1(2026-10-29): '~안입니다'→안건, 빚→부채, 팔 기회→매도할 기회, 오른 날→상승한 날, 시장가→시장 가격, 넓히려→확장하려, 1달러 미만 소수 두 자리
# 사용: python3 script_audio_check.py <narration.txt>   → AUDIO_OK / AUDIO_FAIL
import re, sys
paras = [p.strip() for p in open(sys.argv[1], encoding='utf-8').read().split('\n') if p.strip()]
txt = '\n'.join(paras); bad = []
NUM = '일|이|삼|사|오|육|칠|팔|구|십'
for m in re.finditer(r'리포트\s*(' + NUM + r')\s*부', txt):
    bad.append(f"'{m.group(0)}' → '리포트 {['첫', '두', '세', '네', '다섯', '여섯'][('일이삼사오육'.index(m.group(1)) if m.group(1) in '일이삼사오육' else 0)]} 번째 부분'(일부·오부로 들림)")
for m in re.finditer(r'(?<![가-힣])(' + NUM + r')\s*부(의|에|에서|에는|의 표|로)\b', txt):
    if not re.search(r'리포트\s*$', txt[:m.start()]): bad.append(f"'{m.group(0)}' → 'N번째 부분'(일부·오부로 들림)")
for m in re.finditer(r'국면\s*(에이|비|씨|디)\b', txt):
    bad.append(f"'{m.group(0)}' → '두 번째 국면(공급 소화 단계)'처럼 풀어 읽기(국면비·국면시로 뭉개짐)")
# 고유어 날수(통합 제작·검수 지침 2026-10-29 3.2: '닷새·여드레' 발음 불명확) → 'N 거래일'
for w, n in (('사흘', '삼'), ('나흘', '사'), ('엿새', '육'), ('이레', '칠'), ('여드레', '팔'), ('아흐레', '구')):
    if w in txt: bad.append(f"'{w}' → '{n} 거래일'(발음 불명확, 통합 지침 3.2)")
for w, alt in (('닷새', '오 거래일'), ('쌓인 일감', '수주 잔고'), ('적힌 시가', '적힌 시장 가격')):
    if w in txt: bad.append(f"'{w}' → '{alt}'(TTS·자막이 다르게 들림)")
KN = {'두': 2, '세': 3, '네': 4, '다섯': 5}
hyp = len(set(re.findall(r'(첫|두|세|네) 번째 가설', txt)))
for m in re.finditer(r'(두|세|네|다섯) (시나리오|가설)마다|(두|세|네|다섯) (가지 )?시나리오', txt):
    n = KN[m.group(1) or m.group(3)]
    if hyp and n != hyp and not re.search(r'영상에서 다룬', txt):
        bad.append(f"가설 {hyp}개를 말했는데 '{m.group(0)}' — 다리 문장 '영상에서 다룬 {['', '', '두', '세', '네'][hyp]} 가설 외에 … 모두 {m.group(1) or m.group(3)} 가지는 리포트 표에'")
for i, p in enumerate(paras):
    if re.search(r'몇 번(이었|일)을?까요\?', p):
        near = re.sub(r'[^.?!]*\?', '', ' '.join(paras[i:i + 3]))  # 질문 문장 자체는 빼고
        if not re.search(r'(번|차례) (중|가운데) [가-힣]+ 번|[가-힣]+ 번 모두|[가-힣]+ 번 중', near):
            bad.append(f"문단 {i + 1} '몇 번이었을까요?' 뒤 두 문단 안에 결론 한 줄(N번 중 M번)이 없음 — 상세 표만 리포트로")
# v2.1 Master(2026-10-29, SLNH 46회차 영상 검토): 뜻이 뒤집히거나 숫자로 들리는 말
for m in re.finditer(r'[가-힣]+(는|은|ㄴ|할|하는|올리는|늘리는|푸는|바꾸는) 안(입니다|이|을|과|에|으로|도)(?=\s|[.,?]|$)', txt):
    bad.append(f"'{m.group(0)}' → '…안건…'('푸는 안입니다'가 '푸는 아닙니다'로 들림, v2.1 3.1)")
for w, alt in ((r'빚', '부채·차입금(빛으로 오인, v2.1 1.2)'), (r'팔 기회', "'매도할 기회'(숫자 8로 들림)"), (r'오른 (날|자리|구간)', "'상승한 날·구간'('옳은 날'로 들림)"),
               (r'시장가(?! ?격)', "'시장 가격'('시장과'로 들림)"), (r'넓히려', "'확장하려·늘리려'('널 필요'로 들림)"), (r'달러로 달러로|달러 달러', '단위 중복 낭독')):
    for m in re.finditer(w, txt): bad.append(f"'{m.group(0)}' → {alt}")
# 문장 맨 앞 '희석'은 숨소리와 섞여 '피석'으로 들림(쇼츠 지침 4.2, 2026-10-29) → '주식 희석'
for m in re.finditer(r'(?:^|[.?!]\s+|\n)(희석[^\s]*)', txt): bad.append(f"문장 첫머리 '{m.group(1)}' → '주식 희석 …'('피석'으로 들림)")
# 1달러 미만 가격은 소수 두 자리(영 점 오오 달러): '영 점 오 달러'는 0.55가 0.5로 들린 것일 수 있다
for m in re.finditer(r'영 점 [영일이삼사오육칠팔구] (달러|센트)', txt): bad.append(f"'{m.group(0)}' → 1달러 미만은 소수 두 자리('영 점 오오 달러', v2.1 3.3)")
# 한 문장에 금액·주식 수 두 개(46회차 복기: IREN 문단 7 '삼십사 달러 팔십 센트 … 이십오 달러 오십일 센트', SLNH 문단 4·12·20이
# 녹음에서 숫자가 빠져 tts_asr_check 뒤 다시 녹음) → TTS 전에 두 문장으로 나눈다
_N = r'(?:[영일이삼사오육칠팔구십백천만억]+(?: 점 [영일이삼사오육칠팔구]+)?)'
for _sen in re.split(r'(?<=[.?!])\s+', txt):
    _am = re.findall(_N + r' (?:달러(?: ' + _N + r' 센트)?|만 주|억 주|주)(?![가-힣])', _sen)
    if len(_am) >= 2: bad.append(f"한 문장에 금액·주식 수 {len(_am)}개(녹음에서 숫자 누락 위험) → 두 문장으로: {_sen.strip()[:50]}")
# v2.4(2026-11-02 운영자 TNXP 롱폼 검토, ASR로 확인): 임상 단계 축약·'이의'·'~달러대'·센트·'둔화'·'조달이'·'사들일'
for w, alt in ((r'(?<![가-힣])(일|이|삼)\s?상\s*(임상|이전|시험|결과|성공|단계|진입)|임상\s*(일|이|삼)\s?상(?![가-힣])', "'임상 이 단계'·'세 번째 단계 임상'('이상 임상'·'삼성 임상'으로 들림)"),
               (r'이의(를|가|는| 제기)', "'특허 분쟁'·'특허에 제동'('특허 2'로 들림)"), (r'달러대', "'○ 달러에서 ○ 달러 사이'('달러 되었습니다'로 들림)"),
               (r'(?<![가-힣])둔화', "'성장이 느려지는'('두나·누나'로 들림)"), (r'조달이(?= )', "'조달 부담이'('조다리'로 들림)"),
               (r'사들[이일]', "'매입할'('사드릴'로 들림)"),
               ):
    for m in re.finditer(w, txt): bad.append(f"'{m.group(0)}' → {alt}")
# 센트 읽기는 소수로 바꾸되(v2.4), 소수 두 자리가 같은 숫자(2.22·0.55)는 소수로 읽으면 하나가 삼켜진다('이 점 이이' → '2.2', v2.6 11-02 비교 녹음)
_DUP = {'십일', '이십이', '삼십삼', '사십사', '오십오', '육십육', '칠십칠', '팔십팔', '구십구', '사십이'}  # v2.8: .42('사이'로 들림)도 달러·센트
for m in re.finditer(r'([영일이삼사오육칠팔구십백천]+) 달러 ([일이삼사오육칠팔구십]+) 센트', txt):
    if m.group(2) not in _DUP: bad.append(f"'{m.group(0)}' → '오 점 이팔 달러'처럼 소수로(ASR '57센치'·'28습니다'로 센트가 뭉개짐, 11-02 비교 녹음)")
for m in re.finditer(r'점 ([일이삼사오육칠팔구])\1 달러', txt):
    bad.append(f"'{m.group(0)}' → 같은 숫자 두 자리는 '이 달러 이십이 센트'처럼 달러·센트로('이 점 이이 달러'가 '2.2'로 들림, v2.6)")
# v2.6(운영자 BTQ 롱폼 검토 11-02): 고유어 기간·발음이 뭉개지는 회사명
for w, alt in ((r'열흘|열하루|보름', "'N 거래일' 또는 '십일 일'(고유어 기간은 달력일·거래일이 섞이고 숫자가 들리지 않음)"),
               (r'램\s?리서치', "'반도체 장비 회사'처럼 업종으로('MB서치'·'랩소치'로 들림, 11-02 ASR)"),
               (r'(?:^|[.?!]\s+)인수한', "'지난 ○월 인수한'(문장 첫머리 '인수한'이 '민수한'으로 들린다는 운영자 지적)")):
    for m in re.finditer(w, txt, re.M): bad.append(f"'{m.group(0).strip()}' → {alt}")
# v2.8 Master(운영자 11-02, LAES 51회차 검토)
# 1) 두 자릿수 고유어 수사 금지: '예순네 번'·'쉰세 번'·'서른여섯 곳'·'스무 거래일' → 한자어('육십사 회'·'오십삼 회'·'이십 거래일')
_NAT = r'(?:열|스무|스물|서른|마흔|쉰|예순|일흔|여든|아흔)(?:\s?(?:한|두|세|네|다섯|여섯|일곱|여덟|아홉))?'
for m in re.finditer(r'(?<![가-힣])' + _NAT + r'\s(번|곳|개|명|종목|거래일|회|배|차례|건|해|달)(?![가-힣])', txt):
    bad.append(f"'{m.group(0)}' → 한자어 수사('육십사 회'·'이십 거래일', 두 자릿수 고유어 금지 v2.8 3.1)")
# 2) '점 사이 달러'(.42)는 '사이(between)'로 들림 → 달러·센트, 1달러 미만은 '오십오 센트'
for m in re.finditer(r'점 사이 달러', txt): bad.append(f"'{m.group(0)}' → '일 달러 사십이 센트'처럼 달러·센트로('1.4 사이 달러'로 들림, v2.8)")
for m in re.finditer(r'영 (점 [영일이삼사오육칠팔구]+ 달러|달러 [일이삼사오육칠팔구십]+ 센트)', txt): bad.append(f"'{m.group(0)}' → 1달러 미만은 '오십오 센트'처럼 센트만(v2.8)")
# 3) 치환 사전(v2.8 3.2)
for w, alt in ((r'몫', "'상승분'·'추가 상승 효과'('목숨'으로 들림, v2.9)"), (r'머문다|머물(?:고|러|며|렀)|머문(?= )', "'횡보한다'('머다는'으로 음절 탈락)"),
               (r'새 최저', "'신저가(새로운 최저가)'('세저'로 들림)"), (r'뮌헨', "'독일'('미낸'으로 들림 → '독일 전자 전시회')"),
               (r'박람회', "'전시회'('박남회'로 들림)"),
               (r'(?<![가-힣])(일|이|삼|사|오|육|칠|팔|구|시|십|십일|십이)월 초 (?![에,])[가-힣]+(는|은|가|이)(?=\s)', "'○월 초에, ○○는'(쉼표로 단어 경계, '초스크는'으로 축약)")):
    for m in re.finditer(w, txt): bad.append(f"'{m.group(0)}' → {alt}")
# 4) 대본(TTS 원고)에 아라비아 숫자·로마자 금지: 'QS7001'·'아이온Q' → '보안칩 큐에스 칠천일'·'아이온큐', '7.2%' 꼬리 중복 낭독 방지
for m in re.finditer(r'[A-Za-z]+\d*|\d[\d.,%]*', txt): bad.append(f"'{m.group(0)}' → 한글 독음으로(영문·숫자 발음 누락·'7.2% 2%' 꼬리 중복, v2.8)")
print('\n'.join('AUDIO ' + b for b in bad) if bad else 'AUDIO_OK')
sys.exit(1 if bad else 0)
